import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import ts from 'typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const CORE_DIST = path.join(ROOT, 'packages', 'core', 'dist');
const REPORT_PATH = path.join(ROOT, 'packages', 'core', 'api-contract.md');

const ENTRYPOINTS = [
	{ subpath: '.', file: 'index.d.ts', stability: 'stable' },
	{ subpath: './experimental', file: 'experimental.d.ts', stability: 'experimental' },
	{ subpath: './internal', file: 'internal.d.ts', stability: 'adapter-only' },
];

function declarationHash(contents) {
	return createHash('sha256').update(contents).digest('hex');
}

function describeSymbol(symbol, checker) {
	const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
	const kinds = [];
	if (target.flags & ts.SymbolFlags.Value) kinds.push('value');
	if (target.flags & ts.SymbolFlags.Type) kinds.push('type');
	if (target.flags & ts.SymbolFlags.Namespace) kinds.push('namespace');
	return { name: symbol.getName(), kind: kinds.join(' + ') || 'unknown' };
}

function collectEntrypointExports(program, checker, entrypoint) {
	const filePath = path.join(CORE_DIST, entrypoint.file);
	const sourceFile = program.getSourceFile(filePath);
	if (!sourceFile) throw new Error(`Could not load declaration entrypoint ${filePath}`);
	const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
	if (!moduleSymbol) throw new Error(`Could not resolve declaration module ${filePath}`);
	return checker
		.getExportsOfModule(moduleSymbol)
		.map((symbol) => describeSymbol(symbol, checker))
		.sort((left, right) => left.name.localeCompare(right.name));
}

function createReport() {
	const declarationPaths = ENTRYPOINTS.map((entrypoint) => path.join(CORE_DIST, entrypoint.file));
	for (const declarationPath of declarationPaths) {
		if (!existsSync(declarationPath)) {
			throw new Error(`Missing ${declarationPath}. Build @eregister/open-grid-core before checking the API contract.`);
		}
	}

	const program = ts.createProgram({ rootNames: declarationPaths, options: { skipLibCheck: true } });
	const checker = program.getTypeChecker();
	const sections = ENTRYPOINTS.map((entrypoint) => {
		const declaration = readFileSync(path.join(CORE_DIST, entrypoint.file), 'utf8');
		const symbols = collectEntrypointExports(program, checker, entrypoint);
		return [
			`## \`${entrypoint.subpath}\` — ${entrypoint.stability}`,
			'',
			`Declaration SHA-256: \`${declarationHash(declaration)}\``,
			`Exports (${symbols.length}):`,
			'',
			...symbols.map((symbol) => `- \`${symbol.name}\` — ${symbol.kind}`),
		].join('\n');
	});

	return [
		'# @eregister/open-grid-core API contract',
		'',
		'Generated by `node scripts/check-core-api.mjs --write`; do not edit by hand.',
		'',
		'This checked report locks the emitted declaration content and exported symbol kinds for every published core entrypoint. `.` is the alpha-stable application API, `./experimental` is intentionally unstable, and `./internal` is adapter-only. It does not make adapter-only symbols application APIs.',
		'',
		...sections,
		'',
	].join('\n');
}

async function main() {
	const mode = process.argv[2] ?? '--check';
	if (mode !== '--check' && mode !== '--write') {
		throw new Error('Usage: node scripts/check-core-api.mjs [--check|--write]');
	}

	// Keep the generated contract byte-for-byte compatible with the repository
	// formatting gate so `api:check` and `format:check` cannot disagree.
	const report = await prettier.format(createReport(), { parser: 'markdown' });
	if (mode === '--write') {
		writeFileSync(REPORT_PATH, report);
		process.stdout.write(`Wrote ${path.relative(ROOT, REPORT_PATH)}\n`);
		return;
	}

	if (!existsSync(REPORT_PATH) || readFileSync(REPORT_PATH, 'utf8') !== report) {
		throw new Error(
			`Core declaration API contract changed. Run \"pnpm --filter @eregister/open-grid-core run api:report\" and review ${path.relative(ROOT, REPORT_PATH)}.`
		);
	}
	process.stdout.write('Core declaration API contract is current.\n');
}

await main();
